const phraseRules = Object.entries(germanDisplayPhraseRewrites)
  .sort(([left], [right]) => right.length - left.length)
  .map(
    ([source, replacement]) =>
      [
        new RegExp(
          source
            .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
            .replace(/-/g, "[\\u002d\\u2010\\u2011]"),
          "gu",
        ),
        replacement,
      ] as const,
  );

/** Called only for German display text, before the shared residual dash formatter. */
export function germanDisplayPunctuation(source: string): string {
  return phraseRules.reduce(
    (text, [pattern, replacement]) => text.replace(pattern, replacement),
    source,
  );
}
