/** Dynamic accessible labels use the same reviewed terminology as visible controls. */
export function germanAdministrationLabel(
  source: string,
  translate: (source: string) => string,
): string | undefined {
  const label = source.match(/^Navigation label (\d+)$/);
  if (label) return `Beschriftung für Navigationslink ${label[1]}`;
  const move = source.match(/^Move navigation link (\d+) up$/);
  if (move) return `Navigationslink ${move[1]} nach oben verschieben`;
  const shown = source.match(/^Show (.+) in navigation$/);
  if (shown) return `${translate(shown[1])} in der Navigation anzeigen`;
  const settings = source.match(/^(.+): (Library settings|List settings)$/);
  if (settings) return `${translate(settings[1])}: ${translate(settings[2])}`;
  return undefined;
}
